    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        String nombreTexto = txtNombreSede.getText().trim();
        String aforoTexto = txtAforoSede.getText().trim();
        String estadoTexto = cbEstadoSede.getSelectedItem().toString().trim();

       
        if (nombreTexto.isEmpty() || !nombreTexto.matches("[a-zA-ZáéíóúÁÉÍÓÚnÑ\\s]+")) {
            JOptionPane.showMessageDialog(this, "Nombre inválido.");
            return;
        }
        if (aforoTexto.isEmpty() || !aforoTexto.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "Aforo inválido. Usa solo números.");
            return;
        }

        
        int estadoSQL = 0;
        if (estadoTexto.equals("Operativo")) estadoSQL = 0;
        else if (estadoTexto.equals("Mantenimiento")) estadoSQL = 1;
        else if (estadoTexto.equals("Clausurado")) estadoSQL = 2;

        String sql = "UPDATE Sedes SET Nombre = ?, AforoMaximo = ?, Estado = ? WHERE ID = ?";

        try (Connection con = ConexionSQL.conectar();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, nombreTexto);
            pst.setInt(2, Integer.parseInt(aforoTexto));
            pst.setInt(3, estadoSQL);
            pst.setString(4, idSedeActual);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "¡Sede modificada exitosamente!");
            fueGuardado = true;
            this.dispose(); 

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al modificar en SQL: " + e.getMessage());
        }
    }                                         

