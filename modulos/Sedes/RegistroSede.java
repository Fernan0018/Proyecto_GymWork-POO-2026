    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        String aforoTexto = txtAforo.getText().trim();
        String nombreTexto = txtName.getText().trim();
        String IDTexto = txtID.getText().trim();
        String EstadoTexto = cbEstado.getSelectedItem().toString().trim();
        String UbiGeoTexto = txtLocation.getText().trim();
        
      
        String NombreArchivo = "datos/UbiGeo.txt";
        boolean encontrado = false;
        File archivo = new File(NombreArchivo);
        List<String> codigos = new ArrayList<>();
        try(BufferedReader entrada = new BufferedReader(new FileReader(archivo))){
            String line;
            while((line=entrada.readLine()) !=null){
                String[] datos = line.split(" ", 2);
                codigos.add(datos[0]);
            }
            entrada.close();
            for(int h=0;h<codigos.size();h++){
                if(UbiGeoTexto.equals(codigos.get(h))){
                    encontrado = true;
                }
            }
        }catch (IOException e){
            System.out.println("ERROR");
        }
        
        if(!encontrado){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un codigo de UbiGeo valido.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtLocation.requestFocus();
            return;
        }
        
        
        if(IDTexto.isEmpty() || !IDTexto.matches("SD-\\d{3}")){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un ID válido con el formato SD-001.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtID.requestFocus();
            return;
        }
        
        if(nombreTexto.isEmpty() || !nombreTexto.matches("[a-zA-ZáéíóúÁÉÍÓÚnÑ\\s]+")){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un texto valido para el nombre.", "Error de Validación",javax.swing.JOptionPane.ERROR_MESSAGE);
            txtName.requestFocus();
            return;
        }

        if (aforoTexto.isEmpty() || !aforoTexto.matches("\\d+")) {
          javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un número válido para el Aforo.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtAforo.requestFocus();
            return; 
        }
        
        if(EstadoTexto.equals("ESTADO")){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un campo válido para el estado.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            cbEstado.requestFocus();
            return;
        }
        
        int estadoSQL = 0;
        if (EstadoTexto.equals("Operativo")) {
            estadoSQL = 0;
        } else if (EstadoTexto.equals("Mantenimiento")) {
            estadoSQL = 1;
        } else if (EstadoTexto.equals("Clausurado")) {
            estadoSQL = 2;
        }

       
        String sql = "INSERT INTO Sedes (ID, Nombre, UbiGeo, AforoMaximo, Estado) VALUES (?, ?, ?, ?, ?)";

        try (Connection con = ConexionSQL.conectar();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, IDTexto); 
            pst.setString(2, nombreTexto);
            pst.setString(3, UbiGeoTexto);
            pst.setInt(4, Integer.parseInt(aforoTexto));
            pst.setInt(5, estadoSQL);

            pst.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "¡Sede registrada exitosamente en la base de datos!");
            fueGuardado = true;
            this.dispose();

        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + e.getMessage(), "Error SQL", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }                                         

