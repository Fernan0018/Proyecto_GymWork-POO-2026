    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                          
            String AsuntoTest = txtAsunto.getText().trim();
        String RemitenteTest = txtRemitente.getText().trim();
        String CategoriaTest = txtCategoria.getSelectedItem().toString().trim();
        String PrioridadTest = cbxPrioridad.getSelectedItem().toString().trim();
        
        // VALIDACIONES
        if(AsuntoTest.isEmpty() || !(AsuntoTest.matches("[a-zA-ZáéíóúÁÉÍÓÚnÑ\\s]+"))){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un asunto valido.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtAsunto.requestFocus();
            return;
        }
        if(RemitenteTest.isEmpty() || !(RemitenteTest.matches("[a-zA-ZáéíóúÁÉÍÓÚnÑ\\s]+"))){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa un remitente válido.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtRemitente.requestFocus();
            return;
        }
        if(CategoriaTest.equals("CATEGORIA")){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa una categoría válida.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtCategoria.requestFocus();
            return;
        }
        if(PrioridadTest.equals("PRIORIDAD")){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa una prioridad válida.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            cbxPrioridad.requestFocus();
            return;
        }

        // 1. AUTOGENERAR EL CÓDIGO (Busca el número más alto en SQL)
        int number = 0;
        try (Connection con = ConexionSQL.conectar();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery("SELECT MAX(CAST(SUBSTRING(ID, 4, LEN(ID)) AS INT)) AS MaxNum FROM SOPORTE")) {
            
            if (rs.next()) {
                number = rs.getInt("MaxNum");
            }
        } catch (SQLException e) {
            System.out.println("Error al obtener el ID máximo: " + e.getMessage());
        }
        
        number++; // Le sumamos 1
        String nuevoTicketID = String.format("TK-%03d", number); // Rellena con ceros: TK-003

        // 2. TRADUCTOR INVERSO: De Texto Visual a Números para SQL
        int prioridadSQL = 0; // 0 = Baja
        if (PrioridadTest.equals("Alta")) {
            prioridadSQL = 1; // 1 = Alta
        }

        // 3. ENVIAR A LA NUBE
        String sql = "INSERT INTO SOPORTE (ID, Asunto, Remitente, Categoria, Prioridad, Estado) VALUES (?, ?, ?, ?, ?, ?)";
        
        try (Connection con = ConexionSQL.conectar();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, nuevoTicketID); 
            pst.setString(2, AsuntoTest);
            pst.setString(3, RemitenteTest);
            pst.setString(4, CategoriaTest);
            pst.setInt(5, prioridadSQL); // Inyectamos 0 o 1
            pst.setInt(6, 0); // El Estado es 0 porque nace "Open"

            pst.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "¡Ticket " + nuevoTicketID + " creado exitosamente!");
            
            datosNuevoTicket = new Object[]{nuevoTicketID, AsuntoTest, RemitenteTest, CategoriaTest, PrioridadTest, "Open","..."};
            FueGuardado = true;
            this.dispose();

        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el ticket en SQL: " + e.getMessage(), "Error SQL", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }                                         

